#Different versions of Minecraft can structure the saved NBT data in different ways; data versions
#provide a quick and simple way for Minecraft (as well as third-party tools like JNBT) to figure out
#how the data should be interpreted.
#
#Protocol versions uniquely identify the network protocol version that a particular version of Minecraft uses.
#Different versions of Minecraft can have the same protocol version, in which case they are multiplayer-compatible
